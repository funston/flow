"""`flow`: the workflow as a command an outside agent (Claude Code) runs.

Real git repos and real pytest runs; the CLI is called in-process.
"""
from __future__ import annotations

import io
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from flow import flow_cli, workflow as wf  # noqa: E402


def _repo(tmp_path: Path) -> Path:
    (tmp_path / "tests").mkdir()
    (tmp_path / "tests" / "test_ok.py").write_text("def test_ok():\n    assert True\n")
    subprocess.run(["git", "init", "-q", "-b", "main"], cwd=tmp_path, check=True)
    subprocess.run(["git", "add", "-A"], cwd=tmp_path, check=True)
    subprocess.run(
        ["git", "-c", "user.name=t", "-c", "user.email=t@example.com", "commit", "-qm", "init"],
        cwd=tmp_path, check=True,
    )
    return tmp_path


def _run(repo: Path, *words: str, capsys, stdin: str = "") -> str:
    old = sys.stdin
    sys.stdin = io.StringIO(stdin)
    try:
        flow_cli.main(["--project", str(repo), "--style", "dashed", *words])
    finally:
        sys.stdin = old
    return capsys.readouterr().out


def test_commands_are_spelled_the_way_the_host_agent_has_them(tmp_path, capsys):
    out = _run(_repo(tmp_path), "status", capsys=capsys)
    assert "**Do next:** `/flow-onboard`" in out
    assert "/flow onboard" not in out
    assert out.rstrip().endswith("[flow] phase=onboard ok=true next=/flow-onboard")
    assert flow_cli.dashed("run `/flow` then `/flow repro <id>`") == \
        "run `/flow-status` then `/flow-repro <id>`"


def test_a_model_phase_hands_the_task_to_the_calling_agent(tmp_path, capsys):
    repo = _repo(tmp_path)
    onboard = _run(repo, "onboard", capsys=capsys)
    assert "Baseline: 1 passed" in onboard
    assert flow_cli.AGENT_OPEN in onboard and flow_cli.AGENT_CLOSE in onboard

    issue = _run(repo, "issue", "the total is wrong", capsys=capsys)
    task = issue.split(flow_cli.AGENT_OPEN)[1].split(flow_cli.AGENT_CLOSE)[0]
    assert "the total is wrong" in task
    assert wf.load_state(repo).issue == "the total is wrong"


def test_a_blocked_gate_gives_no_task(tmp_path, capsys):
    out = _run(_repo(tmp_path), "fix", capsys=capsys)
    assert "is blocked" in out and flow_cli.AGENT_OPEN not in out
    assert "ok=false" in out


def test_review_is_handed_over_and_recorded_only_for_the_same_diff(tmp_path, capsys):
    repo = _repo(tmp_path)
    _run(repo, "onboard", capsys=capsys)
    _run(repo, "issue", "ok is wrong", capsys=capsys)
    (repo / "tests" / "test_bug.py").write_text("import mod\n\ndef test_bug():\n    assert mod.f() == 2\n")
    (repo / "mod.py").write_text("def f():\n    return 1\n")
    _run(repo, "repro", "tests/test_bug.py::test_bug", capsys=capsys)
    _run(repo, "fix", capsys=capsys)
    (repo / "mod.py").write_text("def f():\n    return 2\n")
    assert "Verified" in _run(repo, "verify", capsys=capsys)

    review = _run(repo, "review", capsys=capsys)
    assert flow_cli.REVIEW_OPEN in review
    fingerprint = review.split("fingerprint: ")[1].split()[0]
    assert not wf.load_state(repo).done("review")

    recorded = _run(repo, "record-review", fingerprint, "--by", "Claude Code subagent",
                    capsys=capsys, stdin="1. The fix ignores negative input.")
    assert "Review recorded (Claude Code subagent)" in recorded
    state = wf.load_state(repo)
    assert state.done("review")
    assert state.review_findings == "1. The fix ignores negative input."
    assert "**Do next:** `/flow-fix`" in recorded

    # Findings for a diff that has since changed are refused.
    (repo / "mod.py").write_text("def f():\n    return 2  # changed\n")
    stale = _run(repo, "record-review", fingerprint, "--by", "x", capsys=capsys, stdin="late")
    assert "Review not recorded" in stale


def test_help_lists_every_command_including_installed_helpers(tmp_path, monkeypatch, capsys):
    from flow import flow_cli, workflow as wf

    # Every phase the workflow accepts is in the list, so help cannot go stale.
    text = wf.run_flow(tmp_path, "help").message
    for phase in wf._PHASE_FUNCS:
        if not phase.startswith("-"):
            assert f"/flow {phase}" in text, phase
    assert "/flow scope" in text and "Do next:" in text
    assert wf.run_flow(tmp_path, "--help").message == text

    # In Claude Code, the prompt-only helpers installed alongside are listed too.
    commands = tmp_path / ".claude" / "commands"
    commands.mkdir(parents=True)
    (commands / "flow-refocus.md").write_text("---\ndescription: Flow: Stop exploring\n---\nStop.\n")
    (commands / "flow-fix.md").write_text("---\ndescription: x\n---\n<!-- generated by flow/install.py -->\n")
    monkeypatch.setattr(flow_cli.Path, "home", lambda: tmp_path)
    assert flow_cli.main(["--project", str(tmp_path), "--style", "dashed", "help"]) == 0
    out = capsys.readouterr().out
    assert "/flow-refocus" in out and "Stop exploring" in out
    assert "/flow-onboard" in out and "/flow-prs 12 approve" in out
    assert out.count("/flow-fix ") == 1, "the workflow's own commands are not listed twice"


def test_a_feature_end_to_end_through_the_command_line(tmp_path, capsys):
    """Spec in a file (no tracker): plan, acceptance tests that fail because
    the feature is missing, build, verify; with a real repo and real pytest."""
    repo = _repo(tmp_path)
    (repo / "spec.md").write_text(
        "# Shout\n\n`shout(text)` upper-cases text.\n\n"
        "## Acceptance criteria\n- shout('hi') returns 'HI'\n"
    )
    _run(repo, "onboard", capsys=capsys)

    picked = _run(repo, "feature", "spec.md", capsys=capsys)
    assert "**Feature:** Shout" in picked and "Acceptance criteria in the spec: 1" in picked
    assert "Plan this feature against its spec" in picked
    assert "next=/flow-repro" in picked

    recorded = _run(repo, "record-plan", capsys=capsys, stdin="1. Where it fits: shout.py")
    assert "**Plan recorded.**" in recorded and "Linear" not in recorded

    asked = _run(repo, "repro", capsys=capsys)
    assert "tests from the 1 acceptance criteria" in asked
    assert "PLAN (already agreed):\n1. Where it fits: shout.py" in asked

    (repo / "tests" / "test_shout.py").write_text(
        "from shout import shout\n\n\ndef test_shout():\n    assert shout('hi') == 'HI'\n"
    )
    red = _run(repo, "repro", "tests/test_shout.py", capsys=capsys)
    assert "**Acceptance tests are red:**" in red, red
    assert "because the feature does not exist yet" in red

    build = _run(repo, "fix", capsys=capsys)
    assert "**Build:**" in build and "Build this feature" in build

    (repo / "shout.py").write_text("def shout(text):\n    return text.upper()\n")
    verified = _run(repo, "verify", capsys=capsys)
    assert "**Verified:** the acceptance tests pass and nothing else broke." in verified, verified

    review = _run(repo, "review", capsys=capsys)
    assert "checking a new\nfeature against its spec" in review
    assert "Each acceptance criterion in the spec" in review
