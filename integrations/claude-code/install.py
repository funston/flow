#!/usr/bin/env python3
"""Install BACH's gated workflow as Claude Code slash commands.

Each `/flow-<phase>` command makes Claude Code run `bin/bach-flow <phase>`,
which does the deterministic work (tests, gates, state in `.git/`, issue
lookup including Linear) and prints the task for Claude to carry out. The
workflow, its vocabulary and its state file are the same ones BACH's own
`/flow` uses, so a workflow started in one can be continued in the other.

    python3 integrations/claude-code/install.py             # ~/.claude/commands
    python3 integrations/claude-code/install.py --dry-run
    python3 integrations/claude-code/install.py --dest DIR   # e.g. a project's .claude/commands
    python3 integrations/claude-code/install.py --uninstall

Files this script did not generate are never overwritten or removed.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
BACH_FLOW = REPO / "bin" / "bach-flow"
MARKER = "<!-- generated by bach/integrations/claude-code/install.py -->"

# (phase, description, argument hint, extra instructions)
COMMANDS = [
    ("help", "Flow: list every flow command and what it does", "", ""),
    ("status", "Flow: where am I in the workflow, and what do I do next", "", ""),
    ("reset", "Flow: forget the saved progress for this directory", "", ""),
    ("scope", "Flow: work in one directory of a large repository (no argument lists them)",
     "[directory | --clear]", ""),
    ("onboard", "Flow 1/7: map the repo and record the test baseline", "[test command]", ""),
    ("issue", "Flow 2/7: pick an issue (no argument lists them) and trace its root cause",
     "[issue file | ENG-123 | #12 | text]", ""),
    ("feature", "Flow 2/7 for a feature: pick its spec, plan before code, post the plan to the issue",
     "[ENG-123 | issue file | text]", "plan"),
    ("linear", "Flow: list Linear issues to pick from (yours, or a project's)", "[project]", ""),
    ("repro", "Flow 3/7: ask for a failing regression test, or run it by id to confirm it is red",
     "[test id]", ""),
    ("fix", "Flow 4/7: smallest correct fix; after a failed verify or a review, addresses that",
     "[which findings to act on]", ""),
    ("verify", "Flow 5/7: run the regression test and the suite against the baseline", "", ""),
    ("review", "Flow 6/7: independent review of the diff in a fresh subagent", "", "review"),
    ("prs", "Flow: a coworker's pull requests: list, or N to review, then N approve / N merge",
     "[N [test | approve | changes <text> | merge]]", ""),
    ("pr", "Flow 7/7: draft the pull request (--diff shows the changes, --create opens it)",
     "[--diff | --create]", ""),
]

COMMON = """\
Run this with the Bash tool from the repository root, exactly as written,
adding the user's arguments (shown below) after `{phase}`. Quote free text as
a single argument.

    {bach_flow} --style dashed --provider claude-code {phase} <arguments>

User's arguments: $ARGUMENTS

Then:

1. Show the command's output to the user as it is. It is the record of where
   the workflow stands; do not summarise it away or restate it differently.
2. If the output contains an `=== AGENT TASK ===` section, carry out that
   task now, following it exactly.
3. If the output says the phase is blocked, rejected or not verified, stop
   there. Do not work around a gate, do not run a different phase to get
   past it. Never add `--force` or `--create`, and never run `/flow-prs`
   with `approve`, `changes` or `merge`, unless the user typed it: those
   act on GitHub.
4. Say nothing about the flow tool itself: not how it works, not whether it
   changed, not what its files are. Report the work, not the tooling.
5. Do not run further phases on your own, and do not claim tests pass: only
   `/flow-verify` decides that. End by telling the user the "Do next"
   command from the output.
"""

REVIEW = """\
6. If the output contains a `=== REVIEW TASK ===` section, the review must be
   independent of this conversation:
   - Start a fresh subagent with the Agent tool. Give it the review task
     text and nothing else from this conversation, and tell it to read files
     only and change nothing.
   - Show its findings to the user in full.
   - Record them, using the `fingerprint:` value from the review task:

         {bach_flow} --style dashed record-review <fingerprint> --by "Claude Code subagent" <<'FINDINGS'
         <the findings, verbatim>
         FINDINGS

   - Show that command's output. Do not act on the findings yourself: the
     user decides which are real, then runs `/flow-fix`.
"""


PLAN = """\
6. If the task asked for a plan, then as soon as the plan is written, record
   it. This keeps it for the later steps and posts it to the Linear issue as
   a comment:

       {bach_flow} --style dashed record-plan <<'PLAN'
       <the plan, verbatim>
       PLAN

   Show that command's output, and list the plan's open questions for the
   user to answer in the issue.
"""

# Prompt-only helpers ("steering" commands). They carry no gate and run no
# tool; they are installed as they are.
HELPERS = Path(__file__).resolve().parent / "helpers"
HELPER_MARKER = "<!-- flow helper: installed by integrations/claude-code/install.py -->"


def render(phase: str, description: str, hint: str, extra: str) -> str:
    front = ["---", f"description: {description}"]
    if hint:
        front.append(f'argument-hint: "{hint}"')
    front.append(f"allowed-tools: Bash({BACH_FLOW}:*)")
    front.append("---")
    body = COMMON.format(phase=phase, bach_flow=BACH_FLOW)
    if extra == "review":
        body += REVIEW.format(bach_flow=BACH_FLOW)
    if extra == "plan":
        body += PLAN.format(bach_flow=BACH_FLOW)
    return "\n".join(front) + "\n" + MARKER + "\n\n" + body


def ours(path: Path) -> bool:
    text = path.read_text()
    return MARKER in text or HELPER_MARKER in text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dest", type=Path, default=Path.home() / ".claude" / "commands")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--uninstall", action="store_true")
    args = parser.parse_args()

    skipped = 0
    # `/flow` on its own (and `/flow --help`) is the same list as `/flow-help`.
    entries = [("flow", "help", "Flow: list every flow command and what it does (same as /flow-help)", "", "")]
    entries += [(f"flow-{phase}", phase, description, hint, extra) for phase, description, hint, extra in COMMANDS]
    for name, phase, description, hint, extra in entries:
        target = args.dest / f"{name}.md"
        if target.exists() and not ours(target):
            print(f"skip    /{name}: {target} exists and was not generated by this script")
            skipped += 1
            continue
        if args.uninstall:
            if target.exists():
                if not args.dry_run:
                    target.unlink()
                print(f"removed /{name}")
            continue
        if not args.dry_run:
            args.dest.mkdir(parents=True, exist_ok=True)
            target.write_text(render(phase, description, hint, extra))
        print(f"{'would write' if args.dry_run else 'wrote  '} /{name}")
    for source in sorted(HELPERS.glob("flow-*.md")):
        target = args.dest / source.name
        name = source.stem
        if target.exists() and not ours(target):
            print(f"skip    /{name}: {target} exists and was not generated by this script")
            skipped += 1
            continue
        if args.uninstall:
            if target.exists():
                if not args.dry_run:
                    target.unlink()
                print(f"removed /{name}")
            continue
        if not args.dry_run:
            target.write_text(source.read_text())
        print(f"{'would write' if args.dry_run else 'wrote  '} /{name}")
    return 1 if skipped else 0


if __name__ == "__main__":
    sys.exit(main())
