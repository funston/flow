"""`bach-flow`: the `/flow` workflow as a plain command-line tool.

The gated workflow in `bach.ops.workflow` needs no reasoning model of its
own: it runs tests, checks gates and keeps state in the repo. This entry
point exposes it to any agent that can run a shell command, so the same
workflow (same state file, same gates, same issue sources) can be driven
from Claude Code, where the model is the host agent rather than a BACH
provider.

    bach-flow status
    bach-flow issue ENG-123
    bach-flow record-review <fingerprint> --by "<who>"   # findings on stdin

Output is the phase's message. When the phase needs the model, the task
follows between `=== AGENT TASK ===` markers; a review is handed over
between `=== REVIEW TASK ===` markers with the fingerprint to record.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from bach.ops import workflow as wf

AGENT_OPEN, AGENT_CLOSE = "=== AGENT TASK ===", "=== END AGENT TASK ==="
REVIEW_OPEN, REVIEW_CLOSE = "=== REVIEW TASK ===", "=== END REVIEW TASK ==="


def dashed(text: str) -> str:
    """Rewrite `/flow issue` as `/flow-issue`: the spelling used where each
    phase is its own slash command (Claude Code), so the "do next" hints
    name commands that exist there."""
    text = re.sub(r"/flow ([a-z]+)", r"/flow-\1", text)
    return re.sub(r"/flow(?![-\w])", "/flow-status", text)


def installed_helpers(commands_dir: Path) -> list[tuple[str, str]]:
    """Other `/flow-*` slash commands installed next to the workflow's own
    (prompt-only helpers), as (command, description), so `help` is complete."""
    found = []
    if not commands_dir.is_dir():
        return found
    for path in sorted(commands_dir.glob("flow-*.md")):
        text = path.read_text(errors="replace")
        if "generated by bach/integrations" in text:
            continue
        described = re.search(r"^description:\s*(.+)$", text, flags=re.M)
        hint = re.search(r'^argument-hint:\s*"?(.*?)"?\s*$', text, flags=re.M)
        what = re.sub(r"^Flow:\s*", "", described.group(1).strip()) if described else ""
        command = f"/{path.stem}" + (f" {hint.group(1)}" if hint and hint.group(1) else "")
        found.append((command, what))
    return found


def render(result: wf.FlowResult, root: Path, style: str = "") -> str:
    parts = [result.message.rstrip()]
    if result.agent_prompt:
        parts += ["", AGENT_OPEN, result.agent_prompt.rstrip(), AGENT_CLOSE]
    if result.review_prompt:
        parts += [
            "", REVIEW_OPEN,
            f"fingerprint: {result.review_fingerprint}",
            "", result.review_prompt.rstrip(), REVIEW_CLOSE,
        ]
    command, _ = wf.next_step(result.state, root)
    parts += ["", f"[flow] phase={result.state.current()} ok={str(result.ok).lower()} next={command}"]
    text = "\n".join(parts)
    return dashed(text) if style == "dashed" else text


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="bach-flow", description=__doc__.split("\n\n")[0])
    parser.add_argument("--project", default=".", help="repository root (default: current directory)")
    parser.add_argument("--provider", default="", help="name recorded as the author of a fix")
    parser.add_argument("--style", choices=["", "dashed"], default="",
                        help="'dashed' prints commands as /flow-issue instead of /flow issue")
    parser.add_argument("--by", default="", help="record-review: who reviewed")
    parser.add_argument("args", nargs=argparse.REMAINDER, help="phase and its arguments")
    ns = parser.parse_args(argv)
    root = Path(ns.project).expanduser().resolve()
    words = [w for w in ns.args if w != "--"]

    if words and words[0] == "record-review":
        # `--by` may come after the fingerprint; REMAINDER leaves it in words.
        rest = words[1:]
        by = ns.by
        if "--by" in rest:
            at = rest.index("--by")
            by = " ".join(rest[at + 1:at + 2]) or by
            rest = rest[:at] + rest[at + 2:]
        if not rest:
            print("usage: bach-flow record-review <fingerprint> --by <who>   (findings on stdin)")
            return 2
        findings = "" if sys.stdin.isatty() else sys.stdin.read()
        current = wf.diff_fingerprint(wf.project_root(root), wf.review_base(root))
        if rest[0] != current:
            print(
                "Review not recorded: the code changed since this review was "
                "requested, so the findings describe a different diff. Run the "
                "verify and review phases again."
            )
            return 1
        state = wf.record_review(root, rest[0], by or "reviewer", findings)
        out = f"Review recorded ({state.reviewed_by}).\n\n" + wf.run_flow(root, "status").message
        print(dashed(out) if ns.style == "dashed" else out)
        return 0

    if words and words[0] == "record-plan":
        plan = "" if sys.stdin.isatty() else sys.stdin.read()
        ok, out = wf.record_plan(root, plan)
        print(dashed(out) if ns.style == "dashed" else out)
        return 0 if ok else 1

    result = wf.run_flow(root, " ".join(words), provider=ns.provider)
    if words and words[0] in ("help", "--help", "-h") and ns.style == "dashed":
        helpers = installed_helpers(Path.home() / ".claude" / "commands")
        if helpers:
            # Rebuild with the helper group so every column lines up. The
            # helper names are already dashed; shield them from the rewrite.
            where = result.message.split("```")[-1]
            body = wf.help_text([("Steering the agent", [(c.replace("/flow-", "/flow "), w) for c, w in helpers])])
            text = dashed(body + where)
            print(text + f"\n\n[flow] phase={result.state.current()} ok=true next={dashed(wf.next_step(result.state, root)[0])}")
            return 0
    print(render(result, root, ns.style))
    return 0


if __name__ == "__main__":
    sys.exit(main())
